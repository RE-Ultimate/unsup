jq() {
	./.ci/jq "$@"
}

./.ci/brotli -d .ci/jq.br

tag=SNAPSHOT
if [[ -n "$CI_COMMIT_BRANCH" && "$CI_COMMIT_BRANCH" != "trunk" ]]; then
	tag=$tag-$CI_COMMIT_BRANCH
fi

latest=$(cat ci-version.txt)
latestu=$(echo "$latest" | sed 's/+/%2B/g')
apibase='https://git.sleeping.town/api/v1/repos/exa/unsup'
auth="Authorization: token $FORGEJO_KEY"
echo -n 'Delete snapshot release... '
curl -s -X DELETE -H "$auth" $apibase/releases/tags/$tag  >/dev/null && echo 'OK' || echo 'Error, ignoring'
echo -n 'Delete snapshot tag... '
curl -s -X DELETE -H "$auth" $apibase/tags/$tag >/dev/null && echo 'OK' || echo 'Error, ignoring'

echo -n 'Create release... '
resp=$(curl --fail-with-body -s -X POST -H 'Content-Type: application/json' -H "$auth" $apibase/releases --data-raw "$(jq --raw-input --slurp --arg latest $latest --arg commit ${CI_COMMIT_SHA-trunk} --arg tag $tag '
{
	name: "v\($latest)",
	target_commitish: $commit,
	tag_name: $tag,
	draft: true,
	prerelease: true,
	body: "Autogenerated snapshot release.\n\n\(.)\n\n***This contains the latest changes, fresh off the trunk! It may be unstable and/or completely broken.***\n\n**Note**: Snapshots are signed with a different key from releases. See [the \"keys\" directory](https://git.sleeping.town/exa/unsup/src/branch/trunk/keys) in the repo."
}' CHANGELOG.md)" || true)
echo 'OK. Release create response:'
echo "$resp" |jq .
relid=$(echo "$resp" | jq -r .id)

if [[ -z "$relid" || "$relid" == "null" ]]; then
	echo 'Release was not created, exit!'
	exit 1
fi

echo 'Jar attach response:'
curl --fail-with-body -s -X POST -H "$auth" "$apibase/releases/$relid/assets?name=unsup-$latestu.jar" \
	-F "attachment=@build/libs/unsup-$latest.jar" |jq .
echo 'Sig attach response:'
curl --fail-with-body -s -X POST -H "$auth" "$apibase/releases/$relid/assets?name=unsup-$latestu.jar.sig" \
	-F "attachment=@build/libs/unsup-$latest.jar.sig" |jq .
echo 'Component attach response:'
curl --fail-with-body -s -X POST -H "$auth" "$apibase/releases/$relid/assets?name=diy.y2k.unsup.json" \
	-F "attachment=@build/libs/diy.y2k.unsup.json" |jq .

echo 'Undraft response:'
curl --fail-with-body -s -X PATCH -H 'Content-Type: application/json' -H "$auth" "$apibase/releases/$relid" \
	--data-raw '{"draft": false}' |jq .
